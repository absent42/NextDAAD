"""Silicon cards for the part switch keeping the Layer 2 roles.

Part 1 shows picture A (the L2 DMA TEST card), so the front surface is
the second L2 surface; then EXTERN 2 4 switches to part 2. Part 2 opens
buffer mode (GFX 0 4) and stages picture B (DISPLAY 0): the screen must
keep picture A until the GFX 0 2 reveal. A build that resets the roles
on the switch stages B onto the visible surface, so B shows early.

python tests/l2roles/stage_l2roles.py <control.nex> <fix.nex>
Builds into tests/out/l2roles, stages sd/LEGL2RC (control) and
sd/LEGL2R (fix) as complete card roots.
"""
import hashlib, os, shutil, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tests', 'art'))
sys.path.insert(0, os.path.join(ROOT, 'tests', 'text2'))
import mkl2card  # noqa: E402
import gen_region  # noqa: E402

NDRC = os.path.join(ROOT, 'authoring-kit', 'lib', 'ndrc.exe')
OUT = os.path.join(ROOT, 'tests', 'out', 'l2roles')

# 5x7 glyphs for picture B's caption, drawn at mkl2card's scale.
GLYPHS = {
    ' ': ["00000"] * 7,
    'B': ["11110", "10001", "10001", "11110", "10001", "10001", "11110"],
    'C': ["01110", "10001", "10000", "10000", "10000", "10001", "01110"],
    'E': ["11111", "10000", "10000", "11110", "10000", "10000", "11111"],
    'I': ["01110", "00100", "00100", "00100", "00100", "00100", "01110"],
    'P': ["11110", "10001", "10001", "11110", "10000", "10000", "10000"],
    'R': ["11110", "10001", "10001", "11110", "10100", "10010", "10001"],
    'T': ["11111", "00100", "00100", "00100", "00100", "00100", "00100"],
    'U': ["10001", "10001", "10001", "10001", "10001", "10001", "01110"],
}
CAPTION_B = "PICTURE B"


def picture_b():
    """256x128, mkl2card's palette: a solid green field, a black caption
    and a 2px black frame - nothing in it resembles picture A."""
    w, h, s = mkl2card.WIDTH, mkl2card.HEIGHT, 4
    px = [[mkl2card.GREEN] * w for _ in range(h)]
    total = len(CAPTION_B) * (5 * s + s) - s
    x0, top = (w - total) // 2, (h - 7 * s) // 2
    for ch in CAPTION_B:
        for gy, row in enumerate(GLYPHS[ch]):
            for gx, bit in enumerate(row):
                if bit == '1':
                    for sy in range(s):
                        for sx in range(s):
                            px[top + gy * s + sy][x0 + gx * s + sx] = mkl2card.BLACK
        x0 += 6 * s
    for y in range(h):
        for x in range(w):
            if y < 2 or y >= h - 2 or x < 2 or x >= w - 2:
                px[y][x] = mkl2card.BLACK
    flat = bytes(v for row in px for v in row)
    assert 255 not in flat
    return mkl2card.pal_bytes() + flat


def head(name):
    return ''.join(['; ', name, ' - generated by tests/l2roles/stage_l2roles.py; do not edit.\n\n',
                    gen_region.FLAGS, '\n/CTL\n_\n\n/VOC\nMARKE   50      noun\n\n/STX\n',
                    gen_region.stx_section(), '\n'])


TAIL = '''
/OTX
/0 "a marker"

/LTX
/0 "Card."

/CON
/0

/OBJ
/0   0        1 _ _  _ _ _ _ _ _ _ _ _ _ _ _ _ _ _ _  MARKE _
'''


def part1():
    return head('L2PART1') + '/MTX\n/0 ""\n' + TAIL + '''
/PRO 0
> _ _   EQ      102 0
        WINDOW  1
        WINAT   20 0
        WINSIZE 12 80
        CLS
        LET     102 1
> _ _   EQ      102 1
        PICTURE 1
        DISPLAY 0
> _ _   EQ      102 1
        MES     "P1 PICTURE A ON SCREEN#n"
        MES     "P1 PRESS A KEY TO SWITCH#n"
        ANYKEY
        EXTERN  2 4
        MES     "P1 SWITCH F#n"
        END
/END
'''


def part2():
    return head('L2PART2') + '/MTX\n/0 ""\n' + TAIL + '''
/PRO 0
> _ _   EQ      104 0
        WINDOW  1
        WINAT   20 0
        WINSIZE 12 80
        CLS
        LET     104 1
        MES     "P2 BOOT#n"
> _ _   EQ      104 1
        PICTURE 2
        GFX     0 4
        DISPLAY 0
> _ _   EQ      104 1
        MES     "P2 B STAGED - PRESS A KEY#n"
        ANYKEY
        GFX     0 2
        GFX     0 3
        MES     "P2 B REVEALED#n"
        END
/END
'''


def sha(path):
    with open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()


def compile_part(dsf, ddb):
    args = [NDRC, 'nextdaad', 'EN', dsf, ddb, '-v3', '-auto-tokens', '-nxtext']
    r = subprocess.run(args, cwd=OUT, capture_output=True, text=True)
    if r.returncode != 0 or not os.path.exists(os.path.join(OUT, ddb)):
        raise SystemExit('ndrc failed on %s:\n%s%s' % (dsf, r.stdout, r.stderr))


def main(control_nex, fix_nex):
    os.makedirs(OUT, exist_ok=True)
    for name, text in (('L2PART1.DSF', part1()), ('L2PART2.DSF', part2())):
        with open(os.path.join(OUT, name), 'w', newline='\r\n') as f:
            f.write(text)
    compile_part('L2PART1.DSF', 'GAME.DDB')
    compile_part('L2PART2.DSF', 'GAME2.DDB')
    with open(os.path.join(OUT, '001.NXI'), 'wb') as f:
        f.write(mkl2card.pal_bytes() + mkl2card.build())
    with open(os.path.join(OUT, '002.NXI'), 'wb') as f:
        f.write(picture_b())
    for leg, nex in (('LEGL2RC', control_nex), ('LEGL2R', fix_nex)):
        card = os.path.join(ROOT, 'sd', leg)
        if os.path.exists(card):
            shutil.rmtree(card)
        os.makedirs(card)
        shutil.copyfile(nex, os.path.join(card, 'NEXTDAAD.NEX'))
        for f in ('GAME.DDB', 'GAME2.DDB', '001.NXI', '002.NXI'):
            shutil.copyfile(os.path.join(OUT, f), os.path.join(card, f))
        print('sd\\%s' % leg)
        for f in sorted(os.listdir(card)):
            p = os.path.join(card, f)
            print('  %-13s %6d  %s' % (f, os.path.getsize(p), sha(p)[:16]))


if __name__ == '__main__':
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])

"""Cards for the part switch keeping pool C free of the AYS stream.

Part 1 (GAME.DDB, under 64K): "P1 BOOT" and an ANYKEY (the check marks
every free bank outside 20-23 BT_USED there), SFX 1 7 loads 001.AYS
(two 16K banks), "P1 SONG ON", then a parser: JUMP = EXTERN 2 4 into
part 2, "P1 SWITCH F" if refused; LOAD = LOAD 0, "P1 LOAD F" if it fails.
Part 2 (GAME2.DDB) is gen_region's REGION game, over 64K by under 16K
(one pool C bank): "P2 BOOT" at init, location 0 reads "P2 ROOM", SAVE
and LOAD in its parser.

python tests/poolc/stage_poolc.py <control.nex> <test.nex> [<control.map> <test.map>]
Builds into tests/out/poolc, stages sd/LEGPCC (control) and sd/LEGPC
(test) as complete card roots; maps given are copied beside them as
tests/out/poolc/LEGPCC.map and LEGPC.map.
"""
import hashlib, os, shutil, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'tests', 'text2'))
sys.path.insert(0, os.path.join(ROOT, 'tests', 'audio'))
import gen_region  # noqa: E402
import mkays  # noqa: E402

NDRC = os.path.join(ROOT, 'authoring-kit', 'lib', 'ndrc.exe')
OUT = os.path.join(ROOT, 'tests', 'out', 'poolc')
FILES = ('GAME.DDB', 'GAME2.DDB', '001.AYS')


def part1():
    return ''.join(['; PCPART1 - generated by tests/poolc/stage_poolc.py; do not edit.\n\n',
                    gen_region.FLAGS,
                    '\n/CTL\n_\n\n/VOC\nMARKE   50      noun\nLOAD    27      verb\n'
                    'JUMP    40      verb\n\n/STX\n', gen_region.stx_section(), '''
/MTX
/0 ""

/OTX
/0 "a marker"

/LTX
/0 "Part one."

/CON
/0

/OBJ
/0   0        1 _ _  _ _ _ _ _ _ _ _ _ _ _ _ _ _ _ _  MARKE _

/PRO 0
> _ _   EQ      102 0
        WINDOW  1
        WINAT   4 0
        WINSIZE 26 80
        CLS
        MES     "P1 BOOT - PRESS A KEY#n"
        ANYKEY
        SFX     1 7
        MES     "P1 SONG ON - TYPE JUMP OR LOAD#n"
        LET     102 1
> _ _   PROCESS 1

/PRO 1
> _ _   PARSE   0
        REDO
> JUMP  _       MES     "P1 JUMP#n"
                EXTERN  2 4
                MES     "P1 SWITCH F#n"
                END
> LOAD  _       LOAD    0
                MES     "P1 LOAD SAME PART#n"
                REDO
> LOAD  _       MES     "P1 LOAD F#n"
                REDO
> _ _   SYSMESS 8
        REDO
/END
'''])


def part2():
    text = gen_region.region_dsf(False).replace(
        '; REGION - generated by tests/text2/gen_region.py',
        '; PCPART2 - gen_region REGION, edited by tests/poolc/stage_poolc.py')
    for old, new in (('REGION - synthetic text', 'P2 BOOT - synthetic text'),
                     ('Place 0. A bare store room.', 'Place 0. P2 ROOM.'),
                     ('WINAT   20 0\n        WINSIZE 10 32', 'WINAT   4 0\n        WINSIZE 26 80')):
        assert text.count(old) == 1, old
        text = text.replace(old, new)
    return text


def sha(path):
    with open(path, 'rb') as f:
        return hashlib.sha256(f.read()).hexdigest()


def compile_part(dsf, ddb):
    args = [NDRC, 'nextdaad', 'EN', dsf, ddb, '-v3', '-auto-tokens', '-nxtext']
    r = subprocess.run(args, cwd=OUT, capture_output=True, text=True)
    if r.returncode != 0 or not os.path.exists(os.path.join(OUT, ddb)):
        raise SystemExit('ndrc failed on %s:\n%s%s' % (dsf, r.stdout, r.stderr))


def banks_over_64k(size):
    return max(0, (size - 65536 + 16383) // 16384)


def main(control_nex, test_nex, maps):
    os.makedirs(OUT, exist_ok=True)
    for name, text in (('PCPART1.DSF', part1()), ('PCPART2.DSF', part2())):
        with open(os.path.join(OUT, name), 'w', newline='\r\n') as f:
            f.write(text)
    compile_part('PCPART1.DSF', 'GAME.DDB')
    compile_part('PCPART2.DSF', 'GAME2.DDB')
    with open(os.path.join(OUT, '001.AYS'), 'wb') as f:
        f.write(mkays.steady()[0])
    with open(os.path.join(OUT, 'GAME.DDB'), 'rb') as f:
        ddb1 = f.read()
    for code, what in ((b'\x12\x01\x07', 'SFX 1 7'), (b'\x3d\x02\x04', 'EXTERN 2 4'), (b'\x1a\x00', 'LOAD 0')):
        if ddb1.count(code) != 1:
            raise SystemExit('GAME.DDB: %s compiled %d times, expected once' % (what, ddb1.count(code)))
    p1 = os.path.getsize(os.path.join(OUT, 'GAME.DDB'))
    p2 = os.path.getsize(os.path.join(OUT, 'GAME2.DDB'))
    ays = os.path.getsize(os.path.join(OUT, '001.AYS'))
    if banks_over_64k(p1) != 0 or banks_over_64k(p2) != 1:
        raise SystemExit('part sizes %d / %d: need part 1 <= 64K, part 2 one bank over' % (p1, p2))
    if not 16384 < ays <= 3 * 16384:
        raise SystemExit('001.AYS is %d bytes: need 2-3 banks' % ays)
    print('GAME.DDB %d B (0 banks over 64K), GAME2.DDB %d B (1), 001.AYS %d B (%d banks)'
          % (p1, p2, ays, (ays + 16383) // 16384))
    for leg, nex, mp in (('LEGPCC', control_nex, maps[0]), ('LEGPC', test_nex, maps[1])):
        card = os.path.join(ROOT, 'sd', leg)
        if os.path.exists(card):
            shutil.rmtree(card)
        os.makedirs(card)
        shutil.copyfile(nex, os.path.join(card, 'NEXTDAAD.NEX'))
        for f in FILES:
            shutil.copyfile(os.path.join(OUT, f), os.path.join(card, f))
        print('sd\\%s' % leg)
        for f in sorted(os.listdir(card)):
            p = os.path.join(card, f)
            print('  %-13s %6d  %s' % (f, os.path.getsize(p), sha(p)[:16]))
        if mp:
            dst = os.path.join(OUT, leg + '.map')
            shutil.copyfile(mp, dst)
            print('  map -> %s  %s' % (dst, sha(dst)[:16]))


if __name__ == '__main__':
    if len(sys.argv) not in (3, 5):
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3:5] if len(sys.argv) == 5 else (None, None))
